function shuffleArray<T>(items: T[]): T[] {
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

export function getShuffledCards(count = CARDS.length): FalseCard[] {
  return shuffleArray(CARDS)
    .slice(0, count)
    .map(card => {
      const falseStatement = card.statements[card.falseIndex]
      const statements = shuffleArray(card.statements)
      return {
        ...card,
        statements: statements as FalseCard['statements'],
        falseIndex: statements.indexOf(falseStatement),
      }
    })
}
